/**
 * 사람 이름 정리.
 *
 * 구글 워크스페이스 표시이름이 "교사강혜련"처럼 직책+이름으로 붙어 있다. 쿨메신저에서
 * 쓰던 표기가 그대로 넘어온 것인데, 시스템 안에서는 세 가지가 걸린다.
 *
 *  1. 직책이 바뀌어도 표시이름은 안 따라간다. 강혜련 선생님은 연구부장인데 아직 '교사'다.
 *  2. 가나다 정렬이 이름이 아니라 직책 순으로 된다. 47명이 '교사…'로 시작해 ㄱ 구간에
 *     전부 뭉치므로, 명단에서 사람을 찾을 때 눈으로 훑어야 한다.
 *  3. 직책은 teacherAssignments.positionLabel에 이미 구조화돼 있다. 같은 정보를 두 군데
 *     두면서 한쪽만 낡는다.
 *
 * 워크스페이스 표시이름을 학교더러 바꾸라고 할 수는 없으니, 받아 적을 때 이쪽에서
 * 떼어낸다. AuthContext가 로그인마다 표시이름을 users.name에 동기화하기 때문에
 * 여기서 걸러주지 않으면 접두어가 계속 되살아난다.
 */

/**
 * 떼어낼 접두어.
 *
 * '심리학강사한명철'·'일사강사김한조'처럼 과목이 앞에 붙는 경우가 있어 강사와 부장은
 * 앞에 무엇이 오든 받아준다. 학년 부장은 '3학년부장'처럼 숫자로 시작해 숫자도 받는다.
 * 긴 것을 앞에 둬야 '수석교사'가 '교사'로 잘리지 않는다.
 */
const TITLE_PREFIX = /^(수석교사|기간제교사|보건교사|영양교사|[가-힣0-9]{0,6}부장|[가-힣0-9]{0,6}강사|교장|교감|교사|기간제|행정실장|행정|주무관|실무사|영양사|사서|사감)/

/** 한국 사람 이름으로 볼 수 있는 길이. 벗어나면 손대지 않는다. */
const LOOKS_LIKE_NAME = /^[가-힣]{2,5}$/

/**
 * 이름 앞의 직책을 뗀다.
 *
 * 떼고 난 결과가 사람 이름 같지 않으면(공유드라이브 계정처럼) 원본을 그대로 돌려준다.
 * 잘못 자르느니 접두어가 남는 편이 낫다 — 누구인지는 알아볼 수 있어야 한다.
 *
 * @param {string} raw 표시이름
 * @returns {string} 이름만 남긴 값, 또는 자를 수 없으면 원본
 */
export function stripTitlePrefix(raw) {
  const name = (raw || '').trim()
  if (!name) return name

  const bare = name.replace(TITLE_PREFIX, '').trim()
  if (bare === name || !LOOKS_LIKE_NAME.test(bare)) return name
  return bare
}
